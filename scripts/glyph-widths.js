// Measures advance widths of every printable ASCII and Latin-1 character (plus a few
// typographic marks people paste) in Besley 640 and Libre Franklin 600, and writes
// src/js/builder/glyph-widths.js. Run once; re-run only if a font file changes.
//
// It also prints the metrics used for the metric-matched fallback faces in site.css.
//
//   node scripts/glyph-widths.js
import { chromium } from 'playwright';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const font = async (f) => (await readFile(root + 'src/fonts/' + f)).toString('base64');

const codes = [];
for (let c = 32; c <= 126; c++) codes.push(c);
for (let c = 160; c <= 255; c++) codes.push(c);
const extras = [0x2018, 0x2019, 0x201c, 0x201d, 0x2013, 0x2014, 0x2026, 0x2022, 0x2032, 0x2033, 0x20ac, 0x2122];

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent('<!doctype html><title>m</title>');
const result = await page.evaluate(async ({ besley, franklin, codes, extras }) => {
  const load = async (name, b64) => {
    const face = new FontFace(name, `url(data:font/woff2;base64,${b64})`, { weight: '100 900' });
    document.fonts.add(await face.load());
  };
  await load('M Besley', besley);
  await load('M Franklin', franklin);
  const ctx = document.createElement('canvas').getContext('2d');
  const measure = (fontSpec) => {
    ctx.font = fontSpec;
    const w = (c) => Math.round(ctx.measureText(String.fromCharCode(c)).width);
    return { table: codes.map(w), extras: Object.fromEntries(extras.map((c) => [c, w(c)])) };
  };
  const metrics = (fontSpec) => {
    ctx.font = fontSpec;
    const sample = 'The quick brown fox jumps over the lazy dog. Monument signs, built to order 0123456789';
    const m = ctx.measureText(sample);
    return { width: m.width, ascent: m.fontBoundingBoxAscent, descent: m.fontBoundingBoxDescent };
  };
  return {
    serif: measure('640 1000px "M Besley"'),
    sans: measure('600 1000px "M Franklin"'),
    besley400: metrics('400 1000px "M Besley"'),
    franklin400: metrics('400 1000px "M Franklin"'),
    times: metrics('400 1000px "Liberation Serif"'),
    arial: metrics('400 1000px "Liberation Sans"'),
  };
}, { besley: await font('besley-latin-wght-normal.woff2'), franklin: await font('libre-franklin-latin-wght-normal.woff2'), codes, extras });
await browser.close();

const out = `// Generated by scripts/glyph-widths.js. Do not edit by hand.
// Advance widths in thousandths of an em, for the sign lettering:
// SERIF is Besley at weight 640, SANS is Libre Franklin at weight 600.
// Index 0..94 are U+0020..U+007E, 95..190 are U+00A0..U+00FF. EXTRA holds a few typographic marks.
export const SERIF = ${JSON.stringify(result.serif.table)};
export const SANS = ${JSON.stringify(result.sans.table)};
export const SERIF_EXTRA = ${JSON.stringify(result.serif.extras)};
export const SANS_EXTRA = ${JSON.stringify(result.sans.extras)};
`;
await writeFile(root + 'src/js/builder/glyph-widths.js', out);

const fallback = (real, local) => {
  const sizeAdjust = real.width / local.width;
  return {
    'size-adjust': (sizeAdjust * 100).toFixed(2) + '%',
    'ascent-override': ((real.ascent / 1000 / sizeAdjust) * 100).toFixed(2) + '%',
    'descent-override': ((real.descent / 1000 / sizeAdjust) * 100).toFixed(2) + '%',
  };
};
console.log('Wrote src/js/builder/glyph-widths.js');
console.log('Besley fallback (Times New Roman metrics):', fallback(result.besley400, result.times));
console.log('Libre Franklin fallback (Arial metrics):', fallback(result.franklin400, result.arial));
